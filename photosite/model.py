"""Turn scanned files + metadata + config into the site's data model.

`build_catalog` is a pure function of its inputs (no I/O), so the whole
model is testable without touching disk or exiftool.
"""
from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass, field
from datetime import datetime

from .config import Config, ConfigError
from .metadata import Metadata, SourceFile, image_data_hash, location_paths, parse_metadata

RESERVED_SLUGS = {"locations", "about", "contact", "img", "static", "css", "js",
                  "404", "sitemap.xml", "robots.txt", "client", "clients"}
SMALL_WORDS = {"of", "and", "the", "on", "in", "at", "upon", "by", "for", "a", "an",
               "de", "du", "del", "da", "di", "la", "le", "van", "von", "en", "sur"}
SORTS = {"date_desc", "date_asc", "filename"}


def slugify(s: str) -> str:
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def label(segment: str, labels: dict[str, str]) -> str:
    """Display text for a lowercase keyword: override, else smart Title Case."""
    if segment in labels:
        return labels[segment]

    def word(w: str, first: bool) -> str:
        if w in labels:
            return labels[w]
        if re.fullmatch(r"(?:\w[.&])+\w?\.?", w):       # initials: d.c. -> D.C., c&o -> C&O
            return w.upper()
        parts = w.split("-")
        return "-".join(p if (p in SMALL_WORDS and not (first and i == 0)) else p[:1].upper() + p[1:]
                        for i, p in enumerate(parts))
    return " ".join(word(w, i == 0) for i, w in enumerate(segment.split()))


# ----------------------------------------------------------------- objects
@dataclass(eq=False)
class Photo:
    id: str                         # URL slug of the filename stem
    stem: str
    source: SourceFile              # the copy used (newest mtime)
    source_hash: str
    meta: Metadata
    themes: list = field(default_factory=list)        # Theme objects, config order
    locations: list = field(default_factory=list)     # tuples of lowercase segments

    @property
    def date(self) -> datetime:
        return self.meta.date

    @property
    def alt(self) -> str:
        return self.meta.title or self.meta.caption or "Photograph"

    @property
    def canonical_theme(self):
        return self.themes[0] if self.themes else None

    def __repr__(self):
        return f"<Photo {self.id}>"


@dataclass(eq=False)
class Theme:
    folder: str
    name: str
    slug: str
    description: str = ""
    sort: object = "date_desc"
    hidden: bool = False
    cover_stem: str | None = None
    photos: list = field(default_factory=list)
    cover: Photo | None = None


@dataclass(eq=False)
class LocationNode:
    path: tuple
    name: str
    children: dict = field(default_factory=dict)      # segment -> LocationNode
    direct: list = field(default_factory=list)

    def walk(self):
        yield self
        for c in self.children.values():
            yield from c.walk()

    @property
    def all_photos(self) -> list:
        seen, out = set(), []
        for n in self.walk():
            for p in n.direct:
                if p.id not in seen:
                    seen.add(p.id)
                    out.append(p)
        return out


@dataclass(eq=False)
class LocationGallery:
    node: LocationNode
    name: str
    slug: str
    context: list                   # display names of ancestor nodes
    photos: list
    cover: Photo | None
    auto: bool = False              # generated by location_tree, not curated


@dataclass
class Catalog:
    photos: dict                    # id -> Photo (visible photos only)
    themes: list                    # visible themes, display order
    all_themes: list
    tree: LocationNode
    galleries: list
    hero: Photo | None
    warnings: list = field(default_factory=list)
    info: list = field(default_factory=list)

    @property
    def curated_galleries(self) -> list:
        return [g for g in self.galleries if not g.auto]

    def gallery_for_path(self, path: tuple):
        """The gallery for a node (curated first, then location_tree pages)."""
        for g in self.galleries:
            if g.node.path == path:
                return g
        return None

    def breadcrumbs(self, photo: Photo) -> list[list[tuple[str, LocationGallery | None]]]:
        """One crumb trail per place path; crumbs link only where a gallery exists."""
        trails = []
        for path in photo.locations:
            trail, node = [], self.tree
            for seg in path:
                node = node.children[seg]
                trail.append((node.name, self.gallery_for_path(node.path)))
            trails.append(trail)
        return trails


# ------------------------------------------------------------------ helpers
def _newest(photos: list[Photo]) -> Photo | None:
    return max(photos, key=lambda p: (p.date, p.stem), default=None)


def _find(photos, stem: str):
    """A photo by URL id or by filename stem (with or without its ~copy name)."""
    key = slugify(stem)
    return next((p for p in photos if key in (p.id, slugify(p.stem))), None)


def _same_photo(a: SourceFile, b: SourceFile, raw_meta: dict) -> bool:
    """Two exports with the same image data and the metadata the site uses.

    (Byte-identical is too strict: every Lightroom export gets new timestamps and IDs.)
    """
    def key(src):
        m = parse_metadata(raw_meta.get(str(src.path), {}), src)
        return (m.title, m.caption, sorted(m.hierarchical), sorted(m.keywords), m.copyright,
                m.icc_description, m.width, m.height, m.date if m.date_source == "exif" else None)
    try:
        return key(a) == key(b) and image_data_hash(a.path) == image_data_hash(b.path)
    except OSError:
        return False


def cover_tags(hierarchical: list[str], root: str) -> set[str]:
    """Slugs of the collections a photo is tagged to be the cover of ("Covers|Landscapes")."""
    root = root.lower()
    out = set()
    for h in hierarchical:
        segs = [s.strip() for s in h.split("|") if s.strip()]
        if len(segs) == 2 and segs[0].lower() == root:
            out.add(slugify(segs[1]))
    return out


class _CoverTags:
    """Photos tagged Covers|<name>, consumed as themes/galleries/home claim them."""

    def __init__(self, photos, root, info):
        self.by_tag: dict[str, list] = {}
        for p in photos:
            for t in cover_tags(p.meta.hierarchical, root):
                self.by_tag.setdefault(t, []).append(p)
        self.used: set[str] = set()
        self.root, self.info = root, info

    def pick(self, names, pool, what, warnings):
        """The tagged photo for the first matching name; must be in `pool`."""
        for name in names:
            tag = slugify(name)
            if tag not in self.by_tag:
                continue
            self.used.add(tag)
            ids = {p.id for p in pool}
            tagged = [p for p in self.by_tag[tag] if p.id in ids]
            if not tagged:
                warnings.append(f"{what}: the photo tagged {self.root}|{name} isn't in it; using newest")
                return None
            if len(tagged) > 1:
                self.info.append(f"{what}: {len(tagged)} photos tagged {self.root}|{name}; using the newest")
            return _newest(tagged)
        return None

    def unused(self):
        return sorted(t for t in self.by_tag if t not in self.used)


COPY_SEP = "~"


def assign_ids(stems: list[str]) -> dict[str, str]:
    """Filename stem -> URL id.

    Lightroom's template puts the virtual-copy name after a "~"
    ("20221001-DSC9119~Copy 1", originals end in a bare "~"). The copy name is
    left out of the URL unless the original or another copy of the same photo
    is also published; then the original keeps the plain id and each copy gets
    its copy name appended.
    """
    by_base: dict[str, list[tuple[str, str]]] = {}
    for stem in stems:
        base, sep, copy = stem.rpartition(COPY_SEP)
        if not sep:
            base, copy = stem, ""
        by_base.setdefault(slugify(base), []).append((stem, copy))
    ids = {}
    for base, members in by_base.items():
        for stem, copy in members:
            plain = len(members) == 1 or not copy.strip()
            ids[stem] = base if plain else f"{base}-{slugify(copy)}"
    return ids


def sort_photos(photos: list[Photo], sort, warnings: list, where: str) -> list[Photo]:
    by_date = sorted(photos, key=lambda p: (p.date, p.stem), reverse=True)
    if sort in (None, "date_desc"):
        return by_date
    if sort == "date_asc":
        return by_date[::-1]
    if sort == "filename":
        return sorted(photos, key=lambda p: p.stem.lower())
    if isinstance(sort, list):
        listed = []
        for stem in sort:
            p = _find(photos, str(stem))
            if p is None:
                warnings.append(f"{where}: sort list names {stem!r}, which isn't in it")
            elif p not in listed:
                listed.append(p)
        return listed + [p for p in by_date if p not in listed]
    raise ConfigError(f"{where}: unknown sort {sort!r} (use {', '.join(sorted(SORTS))} or a list)")


def resolve_node(spec: str, tree: LocationNode, root: str) -> LocationNode | None:
    """Full path or unique trailing part -> node. Ambiguity is a ConfigError."""
    segs = tuple(s.strip().lower() for s in str(spec).split("|") if s.strip())
    if segs and segs[0] == root.lower():
        segs = segs[1:]
    if not segs:
        raise ConfigError(f"location node {spec!r} is empty")
    nodes = [n for n in tree.walk() if n.path]
    exact = [n for n in nodes if n.path == segs]
    if exact:
        return exact[0]
    matches = [n for n in nodes if n.path[-len(segs):] == segs]
    if len(matches) > 1:
        listing = "\n".join(f"    - node: {'|'.join(n.path)}" for n in matches)
        raise ConfigError(f"location node {spec!r} is ambiguous; it matches:\n{listing}\n"
                          f"  Use the full path in site.yaml.")
    return matches[0] if matches else None


# ------------------------------------------------------------------- build
def build_catalog(config: Config, files: list[SourceFile], raw_meta: dict[str, dict],
                  hashes: dict[str, str]) -> Catalog:
    warnings, info = [], []

    # --- themes, in display order
    folders = sorted({f.theme_folder for f in files})
    for name in config.themes:
        if name not in folders:
            warnings.append(f"theme {name!r} is in site.yaml but has no folder (or no photos)")
    ordered = [n for n in config.themes if n in folders] + [n for n in folders if n not in config.themes]
    themes, slugs = {}, {}
    for folder in ordered:
        o = config.themes.get(folder, {})
        name = str(o.get("name") or folder)
        slug = str(o.get("slug") or slugify(name))
        if slug in RESERVED_SLUGS:
            raise ConfigError(f"theme {folder!r}: slug {slug!r} is reserved; set another `slug`")
        if slug in slugs:
            raise ConfigError(f"themes {slugs[slug]!r} and {folder!r} both have slug {slug!r}")
        slugs[slug] = folder
        sort = o.get("sort", "date_desc")
        if not isinstance(sort, list) and sort not in SORTS:
            raise ConfigError(f"theme {folder!r}: unknown sort {sort!r}")
        themes[folder] = Theme(folder=folder, name=name, slug=slug,
                               description=str(o.get("description") or ""), sort=sort,
                               hidden=bool(o.get("hidden", False)),
                               cover_stem=o.get("cover"))
    theme_rank = {f: i for i, f in enumerate(ordered)}

    # --- photo identity = slug(stem); newest mtime wins
    groups: dict[str, list[SourceFile]] = {}
    for f in files:
        groups.setdefault(slugify(f.stem), []).append(f)
    url_ids = assign_ids(sorted({f.stem for f in files}))
    for folder in folders:
        stems = [f.stem for f in files if f.theme_folder == folder]
        old = [s for s in stems if COPY_SEP not in s]
        if old and len(old) < len(stems):
            warnings.append(f"{folder!r}: {len(old)} of {len(stems)} filenames have no "
                            f"{COPY_SEP!r} (e.g. {old[0]!r}); re-publish the collection")

    photos: dict[str, Photo] = {}
    for pid, copies in sorted(groups.items()):
        stems = sorted({c.stem for c in copies})
        if len(stems) > 1:
            warnings.append(f"filenames {stems} map to the same URL {pid!r}; treated as one photo")
        copies.sort(key=lambda c: (c.mtime_ns, str(c.path)), reverse=True)
        chosen = copies[0]
        h = hashes[str(chosen.path)]
        for c in copies[1:]:
            if hashes[str(c.path)] != h and not _same_photo(chosen, c, raw_meta):
                info.append(f"{chosen.stem}: older copy in {c.theme_folder!r} differs; "
                            f"using the newer one in {chosen.theme_folder!r} (re-publish to sync)")
        visible = sorted({c.theme_folder for c in copies if not themes[c.theme_folder].hidden},
                         key=theme_rank.get)
        if not visible:
            continue                 # only in hidden themes: not on the site
        meta = parse_metadata(raw_meta.get(str(chosen.path), {}), chosen)
        pid = url_ids[chosen.stem]
        if pid in photos:            # e.g. "X~Copy 1" next to an unrelated "X-Copy 1"
            warnings.append(f"{chosen.stem!r} and {photos[pid].stem!r} map to the same URL {pid!r}; "
                            f"using {pid + '-' + str(len(photos))!r} for the first")
            pid = f"{pid}-{len(photos)}"
        p = Photo(id=pid, stem=chosen.stem, source=chosen, source_hash=h, meta=meta,
                  themes=[themes[t] for t in visible],
                  locations=location_paths(meta.hierarchical, config.location_root))
        photos[pid] = p
        for t in p.themes:
            t.photos.append(p)

    # --- per-theme ordering and covers: site.yaml cover, else a Covers|<theme>
    # keyword in Lightroom, else the newest photo
    tags = _CoverTags(photos.values(), config.cover_root, info)
    for t in themes.values():
        t.photos = sort_photos(t.photos, t.sort, warnings, f"theme {t.folder!r}")
        if t.cover_stem:
            t.cover = _find(t.photos, str(t.cover_stem))
            if t.cover is None:
                warnings.append(f"theme {t.folder!r}: cover {t.cover_stem!r} not found; using newest")
        t.cover = (t.cover or tags.pick([t.folder, t.name, t.slug], t.photos, f"theme {t.folder!r}", warnings)
                   or _newest(t.photos))
    visible_themes = [t for t in themes.values() if not t.hidden and t.photos]

    # --- location tree
    tree = LocationNode(path=(), name="")
    for p in photos.values():
        for path in p.locations:
            node = tree
            for i, seg in enumerate(path):
                if seg not in node.children:
                    node.children[seg] = LocationNode(path=path[:i + 1],
                                                      name=label(seg, config.location_labels))
                node = node.children[seg]
            node.direct.append(p)
    _sort_tree(tree)

    # --- curated location galleries
    galleries, gslugs = [], {}
    for g in config.location_galleries:
        node = resolve_node(g["node"], tree, config.location_root)
        if node is None:
            warnings.append(f"location gallery {g['node']!r} matches no published photos; left out")
            continue
        name = str(g.get("name") or node.name)
        slug = str(g.get("slug") or slugify(name))
        if slug in gslugs:
            raise ConfigError(f"location galleries {gslugs[slug]!r} and {g['node']!r} share slug {slug!r}")
        gslugs[slug] = g["node"]
        gphotos = sort_photos(node.all_photos, g.get("sort", "date_desc"), warnings,
                              f"location {g['node']!r}")
        cover = _find(gphotos, str(g["cover"])) if g.get("cover") else None
        if g.get("cover") and cover is None:
            warnings.append(f"location {g['node']!r}: cover {g['cover']!r} not found; using newest")
        if cover is None:
            cover = tags.pick([name, slug, node.name, "|".join(node.path)], gphotos,
                              f"location {g['node']!r}", warnings)
        context, n = [], tree
        for seg in node.path[:-1]:
            n = n.children[seg]
            context.append(n.name)
        galleries.append(LocationGallery(node=node, name=name, slug=slug, context=context,
                                         photos=gphotos, cover=cover or _newest(gphotos)))

    # --- optional page for every node (location_tree: true)
    if config.location_tree:
        have = {g.node.path for g in galleries}
        for node in tree.walk():
            if not node.path or node.path in have:
                continue
            slug = "-".join(slugify(s) for s in node.path)
            while slug in gslugs:
                slug += "-place"
            gslugs[slug] = "|".join(node.path)
            context, n = [], tree
            for seg in node.path[:-1]:
                n = n.children[seg]
                context.append(n.name)
            gphotos = sort_photos(node.all_photos, "date_desc", warnings, slug)
            galleries.append(LocationGallery(node=node, name=node.name, slug=slug, context=context,
                                             photos=gphotos, cover=_newest(gphotos), auto=True))

    # --- home hero
    hero = None
    if config.home.get("hero"):
        hero = _find(photos.values(), str(config.home["hero"]))
        if hero is None:
            warnings.append(f"home hero {config.home['hero']!r} not found; using newest photo")
    hero = (hero or tags.pick(["home"], photos.values(), "home page", warnings)
            or _newest(list(photos.values())))
    for t in tags.unused():
        warnings.append(f"keyword {config.cover_root}|{t} matches no theme, location gallery or 'home'")

    return Catalog(photos=photos, themes=visible_themes, all_themes=list(themes.values()),
                   tree=tree, galleries=galleries, hero=hero, warnings=warnings, info=info)


def _sort_tree(node: LocationNode) -> None:
    node.children = dict(sorted(node.children.items()))
    node.direct.sort(key=lambda p: (p.date, p.stem), reverse=True)
    for c in node.children.values():
        _sort_tree(c)


def format_tree(catalog: Catalog, config: Config) -> str:
    """Text for `build.py locations`: the keyword tree with counts."""
    configured = {}
    for g in catalog.galleries:
        configured[g.node.path] = g.name
    last_seg_count: dict[str, int] = {}
    for n in catalog.tree.walk():
        if n.path:
            last_seg_count[n.path[-1]] = last_seg_count.get(n.path[-1], 0) + 1

    lines = [f"Location tree under {config.location_root!r}  "
             f"(direct / incl. descendants;  * = in location_galleries,  ! = name not unique)", ""]

    def rec(node: LocationNode, depth: int):
        for child in node.children.values():
            seg = child.path[-1]
            mark = f"  * {configured[child.path]}" if child.path in configured else ""
            amb = "  !" if last_seg_count[seg] > 1 else ""
            left = f"{'  ' * depth}{seg}"
            lines.append(f"{left:<48} {len(child.direct):>4} / {len(child.all_photos):<4}{amb}{mark}")
            rec(child, depth + 1)
    rec(catalog.tree, 0)
    untagged = sum(1 for p in catalog.photos.values() if not p.locations)
    lines += ["", f"{len(catalog.photos)} photos, {untagged} with no place keyword"]
    return "\n".join(lines)
